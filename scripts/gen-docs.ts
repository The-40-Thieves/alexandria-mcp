const FEATURE_ENV_NAMES = new Set(FEATURE_ENVS.map((e) => e.name));

function buildEnvBlock(sources: Source[]): string {
  const authVars = new Map<string, string[]>(); // env name -> source names
  for (const s of sources) {
    const env = s.auth?.env;
    if (!env || FEATURE_ENV_NAMES.has(env)) continue;
    const list = authVars.get(env) ?? [];
    list.push(s.name);
    authVars.set(env, list);
  }
  const descByEnv = new Map<string, string>();
  for (const s of sources) {
    const env = s.auth?.env;
    if (env && !descByEnv.has(env)) descByEnv.set(env, s.description);
  }

  const lines: string[] = [
    ENV_START,
    '# Generated by `npm run docs`. Do not edit by hand between these markers.',
    '#',
    '# ── Source-specific keys ────────────────────────────────────────────────',
    '# Each var below is read by src/sources/*.ts and gates one or more sources',
    "# via the registry's `auth` field. A source without a key listed here works",
    '# without any credentials.',
    '',
  ];
  // A required key is often ALSO read optionally by other sources
  // (GITHUB_TOKEN gates githubsearch/githubmcp but merely lifts ghsa's
  // pacing and openiti's search path). Name those too, so the entry does
  // not read as if only the gated sources touch it.
  const optionalUsers = new Map<string, string[]>(); // env name -> source names
  for (const s of sources) {
    for (const env of s.optionalEnv ?? []) {
      const list = optionalUsers.get(env) ?? [];
      list.push(s.name);
      optionalUsers.set(env, list);
    }
  }

  for (const env of [...authVars.keys()].sort()) {
    const usedBy = (authVars.get(env) ?? []).sort().join(', ');
    const desc = descByEnv.get(env) ?? '';
    lines.push(`# ${usedBy}: ${oneLineSummary(desc)}`);
    const alsoOptional = (optionalUsers.get(env) ?? []).sort();
    if (alsoOptional.length > 0) {
      lines.push(`# Also read, but not required, by: ${alsoOptional.join(', ')}.`);
    }
    lines.push(`${env}=`);
    lines.push('');
  }

  // Optional source keys: read by a source but never required by it. Kept
  // in their own section so a reader can tell at a glance which keys unhide
  // a source and which only raise a quota. A name already covered by the
  // required section or by FEATURE_ENVS is not repeated here.
  const optionalVars = new Map<string, string[]>(); // env name -> source names
  for (const [env, names] of optionalUsers) {
    if (FEATURE_ENV_NAMES.has(env) || authVars.has(env)) continue;
    optionalVars.set(env, names);
  }
  if (optionalVars.size > 0) {
    lines.push('# ── Optional source keys ────────────────────────────────────────────────');
    lines.push('# Read by the sources named below but never required by them: each only');
    lines.push('# raises a quota, lifts a rate limit, or unlocks a better backend. Leaving');
    lines.push('# one unset never hides a source.', '');
    for (const env of [...optionalVars.keys()].sort()) {
      const usedBy = (optionalVars.get(env) ?? []).sort().join(', ');
      lines.push(`# ${usedBy}`);
      lines.push(`${env}=`);
      lines.push('');
    }
  }

  lines.push('# ── Feature envs ────────────────────────────────────────────────────────');
  lines.push('# Routing/synthesis provider roles, caching, the web tier, MCP delegation,');
  lines.push('# and vector storage. Every one is optional: the feature it gates is');
  lines.push('# skipped, not failed, when absent.', '');
  for (const { name, comment } of FEATURE_ENVS) {
    lines.push(`# ${comment}`);
    lines.push(`${name}=`);
    lines.push('');
  }

  // Drop the trailing blank line before the end marker.
  while (lines[lines.length - 1] === '') lines.pop();
  lines.push(ENV_END);

  return lines.join('\n');
}

// ── marker splicing ─────────────────────────────────────────────────────────

function spliceMarked(
  content: string,
  startMarker: string,
  endMarker: string,
  inner: string,
): string {
  const startIdx = content.indexOf(startMarker);
  const endIdx = content.indexOf(endMarker);
  if (startIdx === -1 || endIdx === -1 || endIdx < startIdx) {
    throw new Error(
      `Could not find both "${startMarker}" and "${endMarker}" markers to splice content into.`,
    );
  }
  return content.slice(0, startIdx) + inner + content.slice(endIdx + endMarker.length);
}

// ── main ─────────────────────────────────────────────────────────────────────

function computeAll(): { sourcesDoc: string; readme: string; envExample: string } {
  const sources = listSources();
  const sourcesDoc = buildSourcesDoc(sources);

  const readmeCurrent = fs.readFileSync(README_PATH, 'utf8');
  const readmeWithSources = spliceMarked(
    readmeCurrent,
    SOURCES_START,
    SOURCES_END,
    buildReadmeSourcesBlock(sources),
  );
  const readme = applyReadmeSubstitutions(readmeWithSources, sources);

  const envCurrent = fs.readFileSync(ENV_EXAMPLE_PATH, 'utf8');
  const envExample = spliceMarked(envCurrent, ENV_START, ENV_END, buildEnvBlock(sources));

  return { sourcesDoc, readme, envExample };
}

function main(): void {
  const check = process.argv.includes('--check');
  const { sourcesDoc, readme, envExample } = computeAll();

  if (check) {
    const diffs: string[] = [];
    if (
      !fs.existsSync(SOURCES_DOC_PATH) ||
      fs.readFileSync(SOURCES_DOC_PATH, 'utf8') !== sourcesDoc
    )
      diffs.push(SOURCES_DOC_PATH);
    if (fs.readFileSync(README_PATH, 'utf8') !== readme) diffs.push(README_PATH);
    if (fs.readFileSync(ENV_EXAMPLE_PATH, 'utf8') !== envExample) diffs.push(ENV_EXAMPLE_PATH);
    if (diffs.length) {
      console.error(`docs out of date, run \`npm run docs\`: ${diffs.join(', ')}`);
      process.exit(1);
    }
    console.error('docs up to date');
    return;
  }

  fs.writeFileSync(SOURCES_DOC_PATH, sourcesDoc);
  fs.writeFileSync(README_PATH, readme);
  fs.writeFileSync(ENV_EXAMPLE_PATH, envExample);
  console.error(`wrote ${SOURCES_DOC_PATH}, ${README_PATH}, ${ENV_EXAMPLE_PATH}`);
}

if (process.argv[1]?.endsWith('gen-docs.ts') || process.argv[1]?.endsWith('gen-docs.js')) main();

