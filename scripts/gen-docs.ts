// Generates docs/sources.md from the live source registry, and rewrites
// the generated regions of README.md and .env.example between marker
// comments. Hand-written prose outside those markers is left untouched.
//
// `npm run docs` writes the files. `npm run docs -- --check` recomputes
// the same content and exits 1 if any of the three files would change,
// without writing, so CI can catch a registry change that docs weren't
// regenerated for.
import fs from 'node:fs';
import '../src/sources/all.ts';
import { type Cluster, listSources, type SourceKind } from '../src/sources/registry.ts';
import { VERSION } from '../src/version.ts';

const README_PATH = 'README.md';
const ENV_EXAMPLE_PATH = '.env.example';
const SOURCES_DOC_PATH = 'docs/sources.md';

const SOURCES_START = '<!-- sources:start -->';
const SOURCES_END = '<!-- sources:end -->';
const ENV_START = '# env:start';
const ENV_END = '# env:end';

type Source = ReturnType<typeof listSources>[number];

// ── shared helpers ──────────────────────────────────────────────────────────

// Truncates a source description to a single comment line. Deliberately not
// "first sentence": these descriptions are full of abbreviations (St.,
// U.S., v3.) that a period-space split would cut mid-word.
function oneLineSummary(text: string, maxLen = 160): string {
  const oneLine = text.replace(/\s+/g, ' ').trim();
  return oneLine.length > maxLen ? `${oneLine.slice(0, maxLen - 1).trimEnd()}...` : oneLine;
}

function escapeCell(text: string): string {
  return text.replace(/\s+/g, ' ').trim().replace(/\|/g, '\\|');
}

function byCluster(sources: Source[]): Map<Cluster, Source[]> {
  const map = new Map<Cluster, Source[]>();
  for (const s of sources) {
    const list = map.get(s.cluster) ?? [];
    list.push(s);
    map.set(s.cluster, list);
  }
  for (const list of map.values()) list.sort((a, b) => a.name.localeCompare(b.name));
  return map;
}

// ── docs/sources.md ──────────────────────────────────────────────────────────

function buildSourcesDoc(sources: Source[]): string {
  const hiddenCount = sources.filter((s) => s.hidden).length;
  const clusters = byCluster(sources);
  const clusterNames = [...clusters.keys()].sort();

  const lines: string[] = [
    '# Sources',
    '',
    'Generated by `npm run docs` from `src/sources/registry.ts`. Do not edit by hand.',
    '',
    `${sources.length} sources across ${clusterNames.length} clusters (${hiddenCount} hidden pending a key or config not present in this deployment).`,
    '',
  ];

  for (const cluster of clusterNames) {
    const list = clusters.get(cluster) ?? [];
    lines.push(`## ${cluster} (${list.length})`, '');
    lines.push(
      '| Name | Kind | Cluster | Freshness | Auth env | Optional env | Verified | Description |',
    );
    lines.push('|---|---|---|---|---|---|---|---|');
    for (const s of list) {
      const name = s.hidden ? `${s.name} *(hidden)*` : s.name;
      const authEnv = s.auth?.env ?? 'none';
      const optionalEnv = s.optionalEnv?.length ? s.optionalEnv.join(', ') : '-';
      const verified = s.verifiedAt ?? '-';
      lines.push(
        `| ${name} | ${s.kind} | ${s.cluster} | ${s.freshness} | ${authEnv} | ${optionalEnv} | ${verified} | ${escapeCell(s.description)} |`,
      );
    }
    lines.push('');
  }

  lines.push('## Totals', '');
  lines.push('| Cluster | Sources | Hidden |');
  lines.push('|---|---|---|');
  for (const cluster of clusterNames) {
    const list = clusters.get(cluster) ?? [];
    lines.push(`| ${cluster} | ${list.length} | ${list.filter((s) => s.hidden).length} |`);
  }
  lines.push(`| **Total** | ${sources.length} | ${hiddenCount} |`);
  lines.push('');

  return lines.join('\n');
}

// ── README.md ─────────────────────────────────────────────────────────────

function buildReadmeSourcesBlock(sources: Source[]): string {
  const clusters = byCluster(sources);
  const clusterNames = [...clusters.keys()].sort();
  const hiddenCount = sources.filter((s) => s.hidden).length;

  const lines: string[] = [
    SOURCES_START,
    `## Sources (${sources.length})`,
    '',
    `${sources.length} sources across ${clusterNames.length} clusters (${hiddenCount} hidden pending a key or config not present in this deployment). Full per-source detail, including auth env vars and last-verified dates, is generated in [docs/sources.md](docs/sources.md).`,
    '',
    '| Cluster | Sources | Hidden |',
    '|---|---|---|',
  ];
  for (const cluster of clusterNames) {
    const list = clusters.get(cluster) ?? [];
    lines.push(`| ${cluster} | ${list.length} | ${list.filter((s) => s.hidden).length} |`);
  }
  lines.push(`| **Total** | ${sources.length} | ${hiddenCount} |`);
  lines.push('', SOURCES_END);

  return lines.join('\n');
}

function buildHealthExample(sources: Source[]): string {
  const hidden = sources.filter((s) => s.hidden).length;
  const byKind: Record<SourceKind, number> = { rest: 0, hub: 0, rss: 0, mcp: 0, scrape: 0 };
  for (const s of sources) byKind[s.kind]++;
  const kindStr = `{ rest: ${byKind.rest}, hub: ${byKind.hub}, rss: ${byKind.rss}, mcp: ${byKind.mcp}, scrape: ${byKind.scrape} }`;
  // quota/cache are runtime counters (Task 4's StateStore); the doc example
  // shows a freshly-started process (nothing reserved or cached yet) rather
  // than today's actual date, so this line does not drift day to day.
  const quotaStr = '{ day: "2026-09-02", reserved: 0, sources: 0 }';
  const cacheStr = '{ entries: 0 }';
  return `{ status: "ok", version: "${VERSION}", sources: ${sources.length}, visible: ${sources.length - hidden}, hidden: ${hidden}, byKind: ${kindStr}, quota: ${quotaStr}, cache: ${cacheStr}, tools: 9 }`;
}

function applyReadmeSubstitutions(content: string, sources: Source[]): string {
  let out = content;
  out = out.replace(
    /from \d+ public digital libraries/,
    `from ${sources.length} public digital libraries`,
  );
  out = out.replace(
    /List all \d+ sources with descriptions and full-text capabilities/,
    `List all ${sources.length} sources with descriptions and full-text capabilities`,
  );
  out = out.replace(
    /Health check: `GET \/health` returns `\{[^`]*\}`\./,
    `Health check: \`GET /health\` returns \`${buildHealthExample(sources)}\`.`,
  );
  return out;
}

